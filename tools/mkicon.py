"""Builds assets/bootR.ico and src/icon.c from assets/boot.R.png. Usage: mkicon.py <dir with 16/32/48/64/128/256.png from sips>"""
import struct, sys, zlib, os
d = sys.argv[1]
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# .ico with PNG-compressed frames
sizes = [256, 128, 64, 48, 32, 16]
blobs = [open(f"{d}/{n}.png", "rb").read() for n in sizes]
hdr = struct.pack("<HHH", 0, 1, len(sizes)); off = 6 + 16 * len(sizes); ents = b""
for n, b in zip(sizes, blobs):
    ents += struct.pack("<BBBBHHII", n % 256, n % 256, 0, 0, 1, 32, len(b), off); off += len(b)
open(f"{root}/assets/bootR.ico", "wb").write(hdr + ents + b"".join(blobs))

# minimal PNG decoder (8-bit RGBA / RGB, non-interlaced) -> ARGB array
def decode(path):
    b = open(path, "rb").read(); p = 8; idat = b""
    while p < len(b):
        ln, t = struct.unpack(">I4s", b[p:p+8]); data = b[p+8:p+8+ln]; p += 12 + ln
        if t == b"IHDR": w, h, bd, ct, _, _, il = struct.unpack(">IIBBBBB", data)
        elif t == b"IDAT": idat += data
    assert bd == 8 and ct in (2, 6) and il == 0, (bd, ct, il)
    bpp = 4 if ct == 6 else 3; raw = zlib.decompress(idat); stride = w * bpp; prev = bytearray(stride); out = []; q = 0
    for _ in range(h):
        f = raw[q]; line = bytearray(raw[q+1:q+1+stride]); q += 1 + stride
        for i in range(stride):
            a = line[i-bpp] if i >= bpp else 0; c = prev[i-bpp] if i >= bpp else 0; u = prev[i]
            if f == 1: line[i] = (line[i] + a) & 255
            elif f == 2: line[i] = (line[i] + u) & 255
            elif f == 3: line[i] = (line[i] + ((a + u) >> 1)) & 255
            elif f == 4:
                pa, pb, pc = abs(u - c), abs(a - c), abs(a + u - 2 * c)
                pr = a if pa <= pb and pa <= pc else (u if pb <= pc else c)
                line[i] = (line[i] + pr) & 255
        prev = line
        for x in range(w):
            r, g, bl = line[x*bpp], line[x*bpp+1], line[x*bpp+2]; al = line[x*bpp+3] if ct == 6 else 255
            out.append((al << 24) | (r << 16) | (g << 8) | bl)
    return w, h, out

w, h, px = decode(f"{d}/128.png"); assert (w, h) == (128, 128)
with open(f"{root}/src/icon.c", "w") as f:
    f.write('/* Generated by tools/mkicon.py from assets/boot.R.png: 128x128 ARGB. */\n#include "uefi.h"\n#include "bm.h"\n')
    f.write("const UINT32 icon_bootr[128*128]={\n")
    for i in range(0, len(px), 16): f.write(",".join("0x%x" % v for v in px[i:i+16]) + ",\n")
    f.write("};\n")
print("ok", sum(1 for v in px if v >> 24 == 0), "transparent px")
