"""Builds src/logos2.c: a 128x128 alpha mask and one colour for each of the 41 logos in src/assets.c.

The logos in assets.c are 64x64. Drawn at 104 px or more (any screen tall enough for UI scale 2, so 1440p and
4K) a plain bilinear stretch of them looks soft. Each logo is a single-colour shape, so this upsamples its
alpha channel with a bicubic filter and then steepens the edge around the 50% level, which gives a crisp edge
at twice the resolution from the same data. Run from the repository root; needs no extra packages.

    python3 tools/mklogos.py
"""
import re

N, M = 64, 128
t = open("src/assets.c").read()
names = re.search(r"const UINT32 \*const logos\[41\]=\{([^}]*)\}", t).group(1).split(",")
names = [n.strip() for n in names if n.strip()]
assert len(names) == 41


def logo(name):
    m = re.search(r"static const UINT32 %s\[\]=\{([^}]*)\}" % name, t)
    return [int(x, 16) for x in m.group(1).split(",") if x.strip()]


def cubic(p0, p1, p2, p3, f):  # Catmull-Rom
    return p1 + 0.5 * f * (p2 - p0 + f * (2 * p0 - 5 * p1 + 4 * p2 - p3 + f * (3 * (p1 - p2) + p3 - p0)))


def upsample(a):
    def at(x, y):
        return a[min(max(y, 0), N - 1) * N + min(max(x, 0), N - 1)]
    tmp = [[0.0] * N for _ in range(M)]  # rows resampled to M, columns still N
    for oy in range(M):
        sy = (oy + 0.5) * N / M - 0.5
        y0 = int(sy // 1); fy = sy - y0
        for x in range(N):
            tmp[oy][x] = cubic(at(x, y0 - 1), at(x, y0), at(x, y0 + 1), at(x, y0 + 2), fy)
    out = []
    for oy in range(M):
        row = tmp[oy]
        for ox in range(M):
            sx = (ox + 0.5) * N / M - 0.5
            x0 = int(sx // 1); fx = sx - x0
            g = lambda i: row[min(max(i, 0), N - 1)]
            v = cubic(g(x0 - 1), g(x0), g(x0 + 1), g(x0 + 2), fx) / 255.0
            v = (min(max(v, 0.0), 1.0) - 0.5) * 1.8 + 0.5  # steepen the edge about the 50% level
            out.append(int(round(min(max(v, 0.0), 1.0) * 255)))
    return out


masks, colours = [], []
for n in names:
    px = logo(n)
    assert len(px) == N * N, n
    solid = [v & 0xFFFFFF for v in px if (v >> 24) >= 200]
    col = max(set(solid), key=solid.count) if solid else 0xFFFFFF
    colours.append(col)
    masks.append(upsample([v >> 24 for v in px]))

with open("src/logos2.c", "w") as f:
    f.write("/* Generated by tools/mklogos.py from the 64x64 logos in assets.c: 128x128 alpha masks and their colours. */\n")
    f.write('#include "uefi.h"\n#include "bm.h"\n')
    for n, m in zip(names, masks):
        f.write("static const UINT8 hi_%s[]={%s};\n" % (n, ",".join(map(str, m))))
    f.write("const UINT8 *const logos_hi[41]={%s};\n" % ",".join("hi_" + n for n in names))
    f.write("const UINT32 logo_col[41]={%s};\n" % ",".join("0x%06x" % c for c in colours))
print("ok", len(names), "logos")
